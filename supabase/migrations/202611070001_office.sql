-- Upkar Agency: run once in the project's Supabase SQL Editor.
-- No passwords or API keys belong in this file. All data tables are private.
BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'office_backend') THEN
    CREATE ROLE office_backend NOLOGIN NOBYPASSRLS;
  END IF;
END $$;
GRANT office_backend TO postgres;

CREATE SCHEMA IF NOT EXISTS office;
REVOKE ALL ON SCHEMA office FROM PUBLIC;
GRANT USAGE ON SCHEMA office TO office_backend;

CREATE TABLE IF NOT EXISTS office.schema_migrations (
  version integer PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS office.users (
  id text PRIMARY KEY,
  email text UNIQUE NOT NULL,
  password text NOT NULL DEFAULT 'supabase-auth-only',
  role text NOT NULL CHECK (role IN ('owner','operator','viewer'))
);
CREATE TABLE IF NOT EXISTS office.sessions (
  id text PRIMARY KEY,
  user_id text NOT NULL REFERENCES office.users(id) ON DELETE CASCADE,
  csrf text NOT NULL,
  expires double precision NOT NULL
);
CREATE TABLE IF NOT EXISTS office.drafts (
  id text PRIMARY KEY,
  mode text NOT NULL CHECK (mode IN ('demo','live')),
  payload text NOT NULL CHECK (jsonb_typeof(payload::jsonb)='object'),
  status text NOT NULL CHECK (status IN ('draft','demo_saved','cancelled','queued','posting','posted','rejected','needs_review')),
  version integer NOT NULL DEFAULT 1 CHECK (version > 0),
  created double precision NOT NULL,
  updated double precision NOT NULL,
  author text NOT NULL
);
CREATE TABLE IF NOT EXISTS office.jobs (
  id text PRIMARY KEY,
  draft_id text UNIQUE NOT NULL REFERENCES office.drafts(id),
  payload text NOT NULL CHECK (jsonb_typeof(payload::jsonb)='object'),
  status text NOT NULL CHECK (status IN ('queued','leased','posted','rejected','needs_review')),
  lease text,
  leased_at double precision,
  result text,
  created double precision NOT NULL
);
CREATE TABLE IF NOT EXISTS office.snapshots (
  mode text PRIMARY KEY CHECK (mode IN ('demo','live')),
  payload text NOT NULL CHECK (jsonb_typeof(payload::jsonb)='object'),
  updated double precision NOT NULL
);
CREATE TABLE IF NOT EXISTS office.audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor text NOT NULL,
  action text NOT NULL,
  target text NOT NULL,
  at double precision NOT NULL
);
CREATE TABLE IF NOT EXISTS office.report_requests (
  id text PRIMARY KEY,
  report text NOT NULL CHECK (report IN ('daybook','sales','purchases','ledger','receivables','payables','trial','profit','balance','stock')),
  params text NOT NULL CHECK (jsonb_typeof(params::jsonb)='object'),
  status text NOT NULL CHECK (status IN ('queued','reading','ready','failed')),
  result text,
  lease text,
  created double precision NOT NULL,
  updated double precision NOT NULL
);
CREATE TABLE IF NOT EXISTS office.documents (
  id text PRIMARY KEY,
  mode text NOT NULL CHECK (mode IN ('demo','live')),
  name text NOT NULL,
  mime text NOT NULL CHECK (mime IN ('image/jpeg','image/png','application/pdf')),
  path text NOT NULL,
  created double precision NOT NULL
);

CREATE INDEX IF NOT EXISTS drafts_mode_created ON office.drafts(mode,created DESC);
CREATE INDEX IF NOT EXISTS jobs_pending ON office.jobs(status,created);
CREATE INDEX IF NOT EXISTS reports_pending ON office.report_requests(status,created);
CREATE INDEX IF NOT EXISTS sessions_expiry ON office.sessions(expires);

-- The browser has no direct table access. The backend drops to this restricted role
-- inside each transaction and enforces the single-admin session / device permissions.
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA office TO office_backend;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA office TO office_backend;

DO $$
DECLARE
  t text;
  api_role text;
BEGIN
  FOREACH t IN ARRAY ARRAY['schema_migrations','users','sessions','drafts','jobs','snapshots','audit','report_requests','documents']
  LOOP
    EXECUTE format('ALTER TABLE office.%I ENABLE ROW LEVEL SECURITY',t);
    EXECUTE format('ALTER TABLE office.%I FORCE ROW LEVEL SECURITY',t);
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='office' AND tablename=t AND policyname='backend_only') THEN
      EXECUTE format('CREATE POLICY backend_only ON office.%I FOR ALL TO office_backend USING (true) WITH CHECK (true)',t);
    END IF;
  END LOOP;
  FOREACH api_role IN ARRAY ARRAY['anon','authenticated','service_role']
  LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=api_role) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA office FROM %I',api_role);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA office FROM %I',api_role);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA office FROM %I',api_role);
    END IF;
  END LOOP;
END $$;

-- Supabase supplies this schema. Generic PostgreSQL test instances can omit Storage.
DO $$
BEGIN
  IF to_regclass('storage.buckets') IS NOT NULL THEN
    INSERT INTO storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
    VALUES ('office-invoices','office-invoices',false,8388608,ARRAY['image/jpeg','image/png','application/pdf'])
    ON CONFLICT(id) DO UPDATE SET public=false,file_size_limit=8388608,allowed_mime_types=ARRAY['image/jpeg','image/png','application/pdf'];
  END IF;
END $$;

INSERT INTO office.schema_migrations(version) VALUES(1) ON CONFLICT DO NOTHING;
COMMIT;
